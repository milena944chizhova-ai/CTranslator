/*
 * parser.h — интерфейс синтаксического анализатора
 *
 * Метод разбора: расширенное предшествование операторов (operator precedence).
 *   - Операторы верхнего уровня (объявления, присваивания, if, scanf, printf)
 *     разбираются рекурсивным спуском.
 *   - Арифметические выражения и выражения со сравнениями разбираются
 *     методом предшествования по полной матрице 14×14.
 */
#ifndef PARSER_H
#define PARSER_H

#include "token.h"
#include "ast.h"

#define PARSE_ERR_LEN 512

/*
 * parse() — выполняет синтаксический разбор последовательности токенов.
 *
 * Параметры:
 *   tokens — массив токенов (завершается TK_EOF)
 *   count  — число токенов в массиве
 *   err    — буфер для сообщения об ошибке (PARSE_ERR_LEN байт)
 *
 * Возвращает: корневой узел AST или NULL при синтаксической ошибке.
 */
AstNode *parse(Token *tokens, int count, char *err);

#endif /* PARSER_H */
